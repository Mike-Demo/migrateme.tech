import type { CanonicalItem, DestinationRenderer, RenderOutput } from '../canonical';
import { buildManifest } from '../convert';
import { escapeXml, xmlCdata, slugify } from '../shared';

const DEST_FIELDS: Record<string, string> = {
  id: 'guid',
  title: 'title',
  slug: 'link (derived)',
  date: 'pubDate',
  body: 'description (full content inlined)',
  excerpt: 'description (summary)',
  categories: 'category',
  author: 'author / dc:creator',
  featuredImage: 'enclosure (image/*)',
  customFields: 'not representable',
  status: 'not representable',
  type: 'not representable',
};

export const rssAtomDest: DestinationRenderer = {
  id: 'rss-atom',
  label: 'RSS 2.0 feed (.xml)',
  extension: '.xml',
  destFields: DEST_FIELDS,
  render(items): RenderOutput {
    const content = renderFeed(items);
    const manifest = buildManifest(items, 'rss-atom', () => 'feed.xml');
    return { files: [{ path: 'feed.xml', content }], manifest };
  },
};

function renderFeed(items: CanonicalItem[]): string {
  const lines: string[] = [];
  lines.push('<?xml version="1.0" encoding="UTF-8" ?>');
  lines.push(
    '<rss version="2.0" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:content="http://purl.org/rss/1.0/modules/content/">',
  );
  lines.push('<channel>');
  lines.push('  <title>Migrated Content</title>');
  lines.push('  <link>https://example.invalid</link>');
  lines.push('  <description>Feed generated by MigrateMe Universal</description>');
  lines.push(`  <lastBuildDate>${new Date().toUTCString()}</lastBuildDate>`);

  items.forEach((item, index) => {
    const title = item.title || `Item ${index + 1}`;
    const date = item.date ? new Date(item.date).toUTCString() : new Date().toUTCString();
    const link = item.customFields['link'] || `https://example.invalid/${item.slug}`;
    lines.push('  <item>');
    lines.push(`    <title>${escapeXml(title)}</title>`);
    lines.push(`    <link>${escapeXml(link)}</link>`);
    lines.push(
      `    <guid isPermaLink="false">${escapeXml(item.id || slugify(title))}</guid>`,
    );
    lines.push(`    <pubDate>${escapeXml(date)}</pubDate>`);
    if (item.author) {
      lines.push(`    <dc:creator>${escapeXml(item.author)}</dc:creator>`);
    }
    for (const cat of item.categories) {
      lines.push(`    <category>${escapeXml(cat)}</category>`);
    }
    const image =
      item.featuredImage ??
      /<img\s[^>]*src=["']([^"']+)["']/i.exec(item.body)?.[1] ??
      '';
    if (image && /^https?:\/\//i.test(image)) {
      lines.push(
        `    <enclosure url="${escapeXml(image)}" type="image/jpeg" length="0" />`,
      );
    }
    // Excerpt in description; full body in content:encoded when it differs.
    const excerpt = item.excerpt || '';
    lines.push(`    <description>${xmlCdata(excerpt)}</description>`);
    lines.push(`    <content:encoded>${xmlCdata(item.body)}</content:encoded>`);
    lines.push('  </item>');
  });

  lines.push('</channel>');
  lines.push('</rss>');
  return lines.join('\n');
}
