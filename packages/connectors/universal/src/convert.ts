import type {
  CanonicalItem,
  DestinationOutput,
  DestinationRenderer,
  DestFile,
  Manifest,
  RenderOutput,
  Report,
  SourceParser,
} from './canonical';
import { slugify, textToBytes, sha256 } from './shared';
import { LOSSY_FIELD_ROUTES } from './lossy-fields';
import { pairLosses } from './registry';
import { runRoundTrip } from './round-trip';
import type { OmpManifest } from './omp/omp';

export interface ConvertOptions {
  source: SourceParser;
  dest: DestinationRenderer;
  items: CanonicalItem[];
  variant?: string;
  demoMode: boolean;
}

/**
 * Runs the destination renderer, then builds the manifest and report.
 * Field bookkeeping is derived from the parser's declared source fields and
 * the renderer's declared destination fields.
 */
export function runConversion(opts: ConvertOptions): DestinationOutput {
  const { source, dest, items, variant, demoMode } = opts;
  const rendered: RenderOutput = dest.render(items, variant);
  const report = buildReport(source, dest, items, rendered, demoMode);
  const roundTrip = runRoundTrip(
    dest.id,
    items,
    dest.id === 'omp'
      ? [...rendered.files, ...((rendered.extra?.ompFiles ?? []) as DestFile[])]
      : rendered.files,
    rendered.extra,
  );
  if (roundTrip) report.roundTrip = roundTrip;
  const manifest = rendered.manifest;

  manifest.fields = {
    mapped: report.mappedFields,
    defaulted: report.defaultedFields,
    dropped: report.droppedFields,
    lossy: report.lossyFields,
  };
  manifest.demoMode = demoMode;
  manifest.lossyPair = report.lossyFields.length > 0;
  manifest.mappings = {
    mapped: report.mappedFields.map((f) => {
      const [field, target] = f.split(' -> ');
      return { field, target: target ?? '' };
    }),
    defaulted: report.defaultedFields.map((d) => ({ field: d.field, value: d.value })),
    dropped: report.droppedFields.map((d) => ({ field: d.field, reason: d.reason })),
  };
  manifest.provenance = {
    generator: 'MigrateMe Universal',
    originalSource: items[0]?.provenance.sourceFormat,
    demoMode,
    notes: 'Generated by MigrateMe Universal',
  };

  const files: DestFile[] = [...rendered.files];
  if (dest.id !== 'omp') {
    files.push({ path: 'report.md', content: reportToMarkdown(report) });
    manifest.checksums = {};
    for (const f of files) {
      const bytes = (f as { bytes?: Uint8Array }).bytes ?? textToBytes(f.content);
      manifest.checksums[f.path] = sha256(bytes);
    }
    files.push({ path: 'manifest.json', content: JSON.stringify(manifest, null, 2) });
  } else {
    // OMP: manifest.json comes from extra (with checksums); asset payload files
    // live in extra too and must join the bundle. report.md is appended, then
    // checksums are recomputed so every file in the ZIP is covered.
    const ompManifest = rendered.extra?.ompManifest as OmpManifest | undefined;
    const ompFiles = (rendered.extra?.ompFiles ?? []) as DestFile[];
    for (const f of ompFiles) {
      if (!files.some((existing) => existing.path === f.path)) files.push(f);
    }
    if (ompManifest) {
      ompManifest.mappings = {
        mapped: report.mappedFields.map((f) => {
          const [field, target] = f.split(' -> ');
          return { field, target: target ?? '' };
        }),
        defaulted: report.defaultedFields.map((d) => ({ field: d.field, value: d.value })),
        dropped: report.droppedFields.map((d) => ({ field: d.field, reason: d.reason })),
      };
      ompManifest.provenance = {
        ...ompManifest.provenance,
        demoMode,
        notes: 'Generated by MigrateMe Universal',
      };
    }
    files.push({ path: 'report.md', content: reportToMarkdown(report) });
    if (ompManifest) {
      ompManifest.checksums = {};
      for (const f of files) {
        if (f.path === 'manifest.json') continue;
        const bytes = (f as { bytes?: Uint8Array }).bytes ?? textToBytes(f.content);
        ompManifest.checksums[f.path] = sha256(bytes);
      }
      files.unshift({
        path: 'manifest.json',
        content: JSON.stringify(ompManifest, null, 2),
      });
    }
  }

  return { files, manifest, report };
}

function buildReport(
  source: SourceParser,
  dest: DestinationRenderer,
  items: CanonicalItem[],
  rendered: RenderOutput,
  demoMode: boolean,
): Report {
  const mappedFields: string[] = [];
  const notRepresentable: Report['droppedFields'] = [];
  for (const [canon, destField] of Object.entries(dest.destFields)) {
    if (destField.startsWith('not representable')) {
      if (items.some((it) => fieldPresent(it, canon))) {
        notRepresentable.push({ field: canon, reason: destField });
      }
      continue;
    }
    if (items.some((it) => fieldPresent(it, canon))) {
      mappedFields.push(`${canon} -> ${destField}`);
    }
  }

  const defaulted: Report['defaultedFields'] = [];
  const missingSlug = items.filter((it) => !it.slug);
  if (missingSlug.length > 0) {
    defaulted.push({
      field: 'slug',
      reason: `${missingSlug.length} item(s) had no slug in the source`,
      value: 'derived from title',
    });
  }
  const missingDate = items.filter((it) => !it.date);
  if (missingDate.length > 0) {
    defaulted.push({
      field: 'date',
      reason: `${missingDate.length} item(s) had no date in the source`,
      value: 'empty (no date written)',
    });
  }
  const defaultedStatus = items.filter((it) =>
    (it.defaultedFields ?? []).includes('status'),
  );
  if (defaultedStatus.length > 0) {
    defaulted.push({
      field: 'status',
      reason: `${defaultedStatus.length} item(s) had no status in the source`,
      value: 'published',
    });
  }

  const dropped: Report['droppedFields'] = [];
  const lossyFields: Report['lossyFields'] = [];
  const destKnown = new Set(Object.keys(dest.destFields));
  const seenDropped = new Set<string>();
  const seenLossy = new Set<string>();

  const addLossy = (field: string, reason: string) => {
    if (seenLossy.has(field)) return;
    seenLossy.add(field);
    lossyFields.push({ field, reason });
  };

  // Pair-level named losses (e.g. markdown->wxr), then route-level losses
  // named per canonical field ("customFields" losses name the fields they
  // actually apply to, so keep the group label).
  for (const loss of pairLosses(source.id, dest.id)) {
    addLossy(loss.field, loss.reason);
  }
  for (const loss of routeLosses(source, dest)) {
    addLossy(loss.field, loss.reason);
  }

  for (const item of items) {
    for (const key of Object.keys(item.customFields)) {
      const destField = dest.destFields['customFields'];
      if (!destField && !destKnown.has(key) && !seenDropped.has(key)) {
        seenDropped.add(key);
        dropped.push({
          field: key,
          reason: 'source custom field with no matching destination field in this format',
        });
      }
    }
    for (const key of Object.keys(item)) {
      if (key === 'customFields' || key === 'provenance' || key === 'bodyFormat' || key === 'defaultedFields') continue;
      if (!dest.destFields[key] && !seenDropped.has(key)) {
        seenDropped.add(key);
        dropped.push({
          field: key,
          reason: 'canonical field not representable in this destination format',
        });
      }
    }
  }

  const assetsReferenced = new Set<string>();
  const noAltImages: string[] = [];
  const seenNoAlt = new Set<string>();
  for (const item of items) {
    if (item.featuredImage) assetsReferenced.add(item.featuredImage);
    for (const { src, alt } of extractImageRefs(item.body)) {
      assetsReferenced.add(src);
      if (!alt.trim() && !seenNoAlt.has(item.slug)) {
        seenNoAlt.add(item.slug);
        noAltImages.push(item.slug);
      }
    }
  }

  const bundled = new Set(rendered.files.map((f) => f.path));
  const assetsMissing = new Set<string>();
  for (const asset of assetsReferenced) {
    if (/^https?:\/\//i.test(asset) || asset.startsWith('//')) continue;
    const bare = asset.replace(/^\/+/, '').split('?')[0];
    if (!bundled.has(asset) && !bundled.has(bare) && !bundled.has(`assets/${bare.replace(/^.*\//, '')}`)) {
      assetsMissing.add(asset);
    }
  }

  const warnings: string[] = [];
  if (noAltImages.length > 0) {
    warnings.push(
      `Images with no alt text in the source: ${noAltImages.map((s) => `\`${s}\``).join(', ')}. Alt text is an accessibility requirement — add descriptions after migration.`,
    );
  }
  if (assetsMissing.size > 0) {
    warnings.push(
      `${assetsMissing.size} referenced asset(s) were not included in the output bundle: ${Array.from(assetsMissing).slice(0, 10).map((a) => `\`${a}\``).join(', ')}${assetsMissing.size > 10 ? ' and more' : ''}.`,
    );
  }

  return {
    itemsIn: items.length,
    itemsOut: rendered.manifest.itemCount,
    mappedFields,
    defaultedFields: defaulted,
    droppedFields: [...dropped, ...notRepresentable],
    lossyFields,
    assetsReferenced: Array.from(assetsReferenced),
    assetsMissing: Array.from(assetsMissing),
    warnings,
    sourceFormat: source.label,
    destFormat: dest.label,
    demoMode,
    convertedAt: new Date().toISOString(),
  };
}

export function reportToMarkdown(report: Report): string {
  const lines: string[] = [];
  lines.push('# Conversion report');
  lines.push('');
  lines.push(`- Generated: ${report.convertedAt}`);
  lines.push(`- Source: ${report.sourceFormat}`);
  lines.push(`- Destination: ${report.destFormat}`);
  if (report.demoMode) {
    lines.push('- Mode: **Demo Mode** (bundled sample data, not your files)');
  }
  lines.push(`- Items in: ${report.itemsIn}`);
  lines.push(`- Items out: ${report.itemsOut}`);
  lines.push('');
  lines.push('## Fields mapped');
  lines.push('');
  if (report.mappedFields.length === 0) lines.push('_No fields were mapped._');
  else report.mappedFields.forEach((f) => lines.push(`- ${f}`));
  lines.push('');
  lines.push('## Fields defaulted');
  lines.push('');
  if (report.defaultedFields.length === 0) lines.push('_No fields needed defaults._');
  else
    report.defaultedFields.forEach((f) =>
      lines.push(`- \`${f.field}\` — ${f.reason} — default: \`${f.value}\``),
    );
  lines.push('');
  lines.push('## Fields dropped');
  lines.push('');
  if (report.droppedFields.length === 0) lines.push('_No fields were dropped._');
  else
    report.droppedFields.forEach((f) => lines.push(`- \`${f.field}\` — ${f.reason}`));
  lines.push('');
  lines.push('## Lossy conversions (field-by-field)');
  lines.push('');
  if (report.lossyFields.length === 0)
    lines.push('_This pair loses nothing beyond what is mapped above._');
  else
    report.lossyFields.forEach((f) =>
      lines.push(`- \`${f.field}\` — ${f.reason}`),
    );
  lines.push('');
  lines.push('## Assets');
  lines.push('');
  lines.push(`- Referenced: ${report.assetsReferenced.length}`);
  lines.push(`- Missing from bundle: ${report.assetsMissing.length}`);
  report.assetsMissing.forEach((a) => lines.push(`  - \`${a}\``));
  lines.push('');
  lines.push('## Warnings');
  lines.push('');
  if (report.warnings.length === 0) lines.push('_No warnings._');
  else report.warnings.forEach((w) => lines.push(`- ${w}`));
  lines.push('');
  const rt = report.roundTrip;
  if (rt) {
    lines.push('## Round-trip check');
    lines.push('');
    lines.push(
      `The produced ${report.destFormat} output was re-imported in memory with the ${rt.parserLabel} parser and compared against the original items. This check never blocks the download.`,
    );
    lines.push('');
    if (!rt.imported) {
      lines.push(`- Result: the output could not be re-imported — ${rt.note ?? 'unknown error'}`);
    } else {
      lines.push(`- Items compared: ${rt.itemsCompared} of ${rt.itemsExpected}`);
      lines.push(
        `- Items identical on all five fields (title, slug, date, tags, body): ${rt.itemsIdentical}`,
      );
      lines.push('');
      const fieldsWithMismatches = rt.perField.filter((f) => f.mismatches > 0);
      if (fieldsWithMismatches.length === 0) {
        lines.push('_No mismatches on any compared field._');
      } else {
        lines.push('### Mismatches by field');
        lines.push('');
        fieldsWithMismatches.forEach((f) =>
          lines.push(
            `- \`${f.field}\`: ${f.mismatches} item(s) differ (first: \`${f.firstSlug ?? 'unknown'}\`)`,
          ),
        );
      }
      if (rt.note) {
        lines.push('');
        lines.push(`Note: ${rt.note}`);
      }
    }
    lines.push('');
  }
  lines.push('');
  return lines.join('\n');
}

export function buildManifest(
  items: CanonicalItem[],
  destId: string,
  fileFor: (item: CanonicalItem, index: number) => string,
): Manifest {
  return {
    version: 2,
    generator: 'MigrateMe Universal',
    convertedAt: new Date().toISOString(),
    sourceFormat: items[0]?.provenance.sourceFormat ?? 'unknown',
    destFormat: destId,
    demoMode: false,
    itemCount: items.length,
    items: items.map((item, i) => ({
      id: item.id,
      type: item.type,
      title: item.title,
      slug: item.slug,
      date: item.date,
      status: item.status,
      file: fileFor(item, i),
    })),
    fields: { mapped: [], defaulted: [], dropped: [], lossy: [] },
    lossyPair: false,
    mappings: { mapped: [], defaulted: [], dropped: [] },
    provenance: { generator: 'MigrateMe Universal' },
    checksums: {},
  };
}

function fieldPresent(item: CanonicalItem, canon: string): boolean {
  const value = (item as unknown as Record<string, unknown>)[canon];
  if (canon === 'customFields') return Object.keys(item.customFields).length > 0;
  if (Array.isArray(value)) return value.length > 0;
  return value !== null && value !== undefined && value !== '';
}

interface FieldLoss {
  field: string;
  reason: string;
}

/**
 * Lossy field notes for this source->dest pair, from the LOSSY_FIELD_ROUTES
 * table (source-declared and dest-declared field losses).
 */
function routeLosses(source: SourceParser, dest: DestinationRenderer): FieldLoss[] {
  const losses: FieldLoss[] = [];
  const srcLosses = LOSSY_FIELD_ROUTES[source.id];
  if (srcLosses) {
    for (const [field, reason] of Object.entries(srcLosses)) {
      losses.push({ field, reason });
    }
  }
  const destLosses = LOSSY_FIELD_ROUTES[`*->${dest.id}`];
  if (destLosses) {
    for (const [field, reason] of Object.entries(destLosses)) {
      losses.push({ field, reason });
    }
  }
  return losses;
}

function extractImageRefs(body: string): { src: string; alt: string }[] {
  const results: { src: string; alt: string }[] = [];
  let m: RegExpExecArray | null;
  const htmlImg = /<img\s[^>]*>/gi;
  while ((m = htmlImg.exec(body))) {
    const tag = m[0];
    const src = /\bsrc\s*=\s*["']([^"']+)["']/i.exec(tag)?.[1] ?? '';
    const alt = /\balt\s*=\s*["']([^"']*)["']/i.exec(tag)?.[1] ?? '';
    if (src) results.push({ src, alt });
  }
  const mdImg = /!\[([^\]]*)\]\(([^)\s]+)[^)]*\)/g;
  while ((m = mdImg.exec(body))) {
    results.push({ src: m[2], alt: m[1] });
  }
  return results;
}

